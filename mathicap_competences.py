def competences_par_question(exercice):
    """Retourne {numéro_pédagogique: [type de tâche]}, ou {} si non fiable.

    Les modèles inconnus, partiellement annotés ou modifiés ne sont PAS
    automatiquement classés à partir de la position ou de mots-clés.
    """
    if not isinstance(exercice, dict):
        return {}
    modele = exercice.get("id")
    if modele not in CODES_PAR_MODELE:
        return {}
    champs = exercice.get("champs_reponse")
    if not isinstance(champs, list):
        return {}
    schema = []
    for c in champs:
        if not isinstance(c, dict):
            return {}
        schema.append((c.get("question"), c.get("id"), c.get("type")))
    if tuple(schema) != CHAMPS_PAR_MODELE[modele]:
        return {}
    if any(c.get("libelle", "") not in LIBELLES_ACCEPTES_PAR_MODELE[modele][i]
           for i, c in enumerate(champs)):
        return {}
    codes = CODES_PAR_MODELE[modele].split()
    return {i + 1: [CATEGORIES[code]] for i, code in enumerate(codes)}
